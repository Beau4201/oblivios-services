"""Checks the licences of the packages in the daemon's Cargo.lock and keeps NOTICE current.

    cargo metadata --locked --offline --format-version 1 | tools/check-licences.py [--write]

(`tools/check-licences.sh` runs `cargo metadata` on the build server.) A package passes when its SPDX expression can be
satisfied using only the terms in ALLOWED: for `A OR B` one side is enough, for `A AND B` both are needed. A package with no
expression fails, except the three vendored Onionmasq crates, whose licence (`MIT OR Apache-2.0`) is recorded in SOURCE.md.
NOTICE lists every package with its version and expression, sorted, and must equal what the lock file says: a changed lock file
without a changed NOTICE is an error. The licence texts of the packages are not bundled here (see RISKS.md).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ALLOWED = {
    "MIT", "Apache-2.0", "BSD-1-Clause", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Unicode-3.0", "Zlib", "0BSD", "CC0-1.0",
    "MIT-0", "Unlicense", "MPL-2.0", "LLVM-exception",
}
VENDORED = {"onion-tunnel", "onionmasq-device-testing", "simple-proc-net"}
VENDORED_LICENCE = "MIT OR Apache-2.0"


def normalise(expr):
    """The old `A/B` forms of crates.io become `A OR B`."""
    return re.sub(r"\s*/\s*", " OR ", expr)


def tokens(expr):
    return re.findall(r"\(|\)|[A-Za-z0-9.+-]+", expr)


def satisfied(expr):
    """Can the expression be met with ALLOWED terms only? A small recursive-descent parser: OR < AND < WITH."""
    toks = tokens(normalise(expr))
    pos = 0

    def peek():
        return toks[pos] if pos < len(toks) else None

    def take():
        nonlocal pos
        pos += 1
        return toks[pos - 1]

    def atom():
        t = take()
        if t == "(":
            v = parse_or()
            if take() != ")":
                raise ValueError("unbalanced")
            return v
        ok = t in ALLOWED
        if peek() == "WITH":
            take()
            ok = ok and take() in ALLOWED
        return ok

    def parse_and():
        v = atom()
        while peek() == "AND":
            take()
            v = atom() and v
        return v

    def parse_or():
        v = parse_and()
        while peek() == "OR":
            take()
            v = parse_and() or v
        return v

    v = parse_or()
    if pos != len(toks):
        raise ValueError("trailing tokens")
    return v


def main():
    meta = json.load(sys.stdin)
    rows, failures = [], []
    for p in meta["packages"]:
        expr = p.get("license")
        if not expr:
            if p["name"] in VENDORED and p.get("source") is None:
                expr = VENDORED_LICENCE
            elif p.get("source") is None:
                expr = "Apache-2.0"  # the daemon's own crate (Cargo.toml: license = "Apache-2.0")
            else:
                failures.append(f"{p['name']} {p['version']}: no licence expression")
                continue
        try:
            ok = satisfied(expr)
        except ValueError:
            ok = False
        if not ok:
            failures.append(f"{p['name']} {p['version']}: {expr!r} cannot be met with the allowed terms")
        rows.append((p["name"], p["version"], expr))
    rows.sort()
    text = (
        "# Third-party packages of the exit daemon: name, version, SPDX licence expression.\n"
        "# Generated by tools/check-licences.py from Cargo.lock; do not edit by hand.\n"
        + "".join(f"{n} {v} {e}\n" for n, v, e in rows)
    )
    path = os.path.join(ROOT, "NOTICE")
    if "--write" in sys.argv:
        open(path, "w", encoding="utf-8", newline="\n").write(text)
    elif not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        failures.append("NOTICE does not match Cargo.lock (run with --write and commit the result)")
    for f in failures:
        print("FAIL:", f)
    if failures:
        return 1
    print(f"licences: {len(rows)} packages, all expressions can be met with the allowed terms; NOTICE is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
